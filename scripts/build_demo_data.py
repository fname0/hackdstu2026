def main():
    wb = openpyxl.load_workbook(XLSX, data_only=True)
    msp, invest = wb.worksheets[0], wb.worksheets[1]

    companies, unknown = [], collections.Counter()
    existing_inns = set()

    for r in msp.iter_rows(min_row=2, values_only=True):
        if not r[0]:
            continue
        key = norm(r[9]) or norm(r[8])
        if key not in PLACES:
            unknown[key] += 1
            continue

        inn = str(r[5] or "").strip()
        existing_inns.add(inn)
        subj_type = "ЮЛ" if r[2] == "Юридическое лицо" else "ИП"
        cat = r[3] or "Микропредприятие"
        ind = industry(r[6])
        place = PLACES[key][0]
        is_new = r[11] == "Да"
        staff = r[21]
        has_lic = r[17] == "Да"
        inc_date = str(r[12] or "")

        h_closed = stable_hash("closed:" + inn)
        is_closed = bool(r[13]) or (not is_new and not staff and not has_lic and (h_closed % 14 == 0))

        reloc = detect_relocation(inn, place, has_lic)
        fact_place = reloc["factPlace"] if reloc else place

        rev, growth = estimate_revenue(inn, cat, subj_type, staff, ind)
        if is_closed:
            growth = -100

        lat, lon = jitter_coords(fact_place, inn)

        comp = {
            "name": r[1],
            "inn": inn,
            "type": subj_type,
            "cat": cat,
            "okved": r[6],
            "ind": ind,
            "place": fact_place,
            "lat": lat,
            "lon": lon,
            "isNew": is_new,
            "staff": staff,
            "our": True,
            "closed": is_closed,
            "rev": rev,
            "growth": growth,
            "incDate": inc_date,
        }
        if reloc:
            comp.update(reloc)
        companies.append(comp)

    potential = generate_potential_msp(existing_inns, count=1240)
    all_companies = companies + potential

    projects = []
    for r in invest.iter_rows(min_row=2, values_only=True):
        if not r[0]:
            continue
        projects.append({
            "mo": PLACES.get(norm(r[1]), (r[1],))[0],
            "key": r[3] == "Да",
            "initiator": r[4],
            "title": re.sub(r"\s+", " ", str(r[5] or "")).strip(),
            "start": int(r[6]) if r[6] else None,
            "finish": int(r[7]) if r[7] else None,
            "sum": float(r[8] or 0),
            "jobs": r[9],
        })

    places = {v[0]: [v[1], v[2]] for v in PLACES.values()}
    OUT.write_text(
        f"window.RT_DATA = {json.dumps({'companies': all_companies, 'projects': projects, 'places': places}, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    our_cnt = sum(1 for c in all_companies if c["our"])
    closed_cnt = sum(1 for c in all_companies if c["our"] and c["closed"])
    reloc_cnt = sum(1 for c in all_companies if c.get("relocType"))
    print(
        f"total={len(all_companies)} our={our_cnt} (closed={closed_cnt}) "
        f"potential={len(potential)} relocated(*)={reloc_cnt} projects={len(projects)} unknown={dict(unknown)}",
        file=sys.stderr,
    )

if __name__ == "__main__":
    main()
