_SPACE = re.compile(r"\s+")


def _quote(text: str, m: re.Match, width: int = 40) -> str:
    """Короткая цитата вокруг совпадения: «…производительностью 10 тонн в час…»."""
    a, b = max(0, m.start() - width), min(len(text), m.end() + width)
    return ("…" if a else "") + text[a:b].strip() + ("…" if b < len(text) else "")


def classify(initiator: str, title: str) -> dict:
    text = _SPACE.sub(" ", title).strip()
    low = f"{initiator} {text}".lower()
    industry, industry_reason = "Прочее", None
    # Сначала по названию проекта, и только потом по инициатору («Агротранс» строит ФОК, а не ферму)
    for haystack in (text.lower(), low):
        hit = next(((n, m) for n, rx in INDUSTRY_RULES if (m := re.search(rx, haystack))), None)
        if hit:
            industry, industry_reason = hit[0], _quote(text, hit[1]) if haystack is not low else hit[1].group(0)
            break

    needs: dict[str, dict] = {}
    low_title = text.lower()
    for need, rx, offer in NEED_RULES:
        if need in needs:
            continue
        if m := re.search(rx, low_title):
            needs[need] = {"need": need, "label": NEED_LABELS[need], "offer": offer, "quote": _quote(text, m)}
    return {"industry": industry, "industry_reason": industry_reason,
            "needs": [needs[k] for k in NEED_LABELS if k in needs]}
